bool suite_view(int index, View* out) {
	if (index < 0 || index >= SUITE_COUNT) return false;
	const SuiteView* b = &SUITE[index];
	View v;
	if (!point_parse(&v.centre, b->re, b->im)) return false;
	v.scale_log2 = b->log10_size * LOG2_10 + num_log2(BOOKMARK_FRAME_SIZES / (double)MB_SCREEN_WIDTH);
	*out = v;
	return true;
}

int suite_period(int index) {
	return index >= 0 && index < SUITE_COUNT ? SUITE[index].period : 0;
}

// THE PLAYER'S BOOKMARKS (the lead's curation, design.md §11.2): a name, the centre as exact decimals,
// and the width of the real axis across the screen; or a view of the deep suite above by its index;
// or home. One row each, so replacing a bookmark is replacing a line.
#define BOOKMARK_HOME (-1)   // suite: home, as view_home
#define BOOKMARK_PLACE (-2)  // suite: the centre and width of the row itself
typedef struct {
	const char* name;
	int suite;
	const char* re;
	const char* im;
	double width;
} Bookmark;

static const Bookmark BOOKMARKS[BOOKMARK_COUNT] = {
	{"Home", BOOKMARK_HOME, "", "", 0.0},
	{"Elephant valley", BOOKMARK_PLACE, "0.2925", "0.015", 1e-2},
	{"Seahorse valley", BOOKMARK_PLACE, "-0.7463", "0.1102", 5e-3},
	{"Triple spiral", BOOKMARK_PLACE, "-0.08896", "0.65425", 4e-3},
	{"Dendrite", BOOKMARK_PLACE, "-0.10109636", "0.95628651", 2e-2},
	{"The double spiral", BOOKMARK_PLACE, "-0.7436438870371585", "0.1318259042053121", 4.1e-9},
	{"Julia island", BOOKMARK_PLACE, "-1.768778833", "-0.001738996", 8e-8},
	{"A minibrot at 10^-29", 0, "", "", 0.0},
	{"A minibrot at 10^-130", 2, "", "", 0.0},
};

bool bookmark_view(int index, View* out) {
	if (index < 0 || index >= BOOKMARK_COUNT) return false;
	const Bookmark* b = &BOOKMARKS[index];
	if (b->suite == BOOKMARK_HOME) {
		*out = view_home();
		return true;
	}
	if (b->suite >= 0) return suite_view(b->suite, out);
	View v;
	if (!point_parse(&v.centre, b->re, b->im)) return false;
	v.scale_log2 = num_log2(b->width / (double)MB_SCREEN_WIDTH);
	*out = v;
	return true;
}

const char* bookmark_name(int index) {
	return index >= 0 && index < BOOKMARK_COUNT ? BOOKMARKS[index].name : "";
}
